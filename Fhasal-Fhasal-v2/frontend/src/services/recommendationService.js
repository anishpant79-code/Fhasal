export const evaluateFieldSuitability = ({
    field,
    temperature = null,
    rainfall = null,
    season = getCurrentGrowingSeason(),
}) => {
    const fieldSoil = field?.soilType || ''

    return REFERENCE_CROPS.map((crop) => {
        const evaluation = calculateCropSuitability({
            crop,
            fieldSoil,
            averageTemperature: temperature,
            weeklyRainfall: rainfall,
            currentSeason: season,
        })

        return {
            ...crop,
            suitability: evaluation,
        }
    }).sort((a, b) => (b.suitability.score || 0) - (a.suitability.score || 0))
}
