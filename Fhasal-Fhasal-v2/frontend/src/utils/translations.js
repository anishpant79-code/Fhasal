const normalizeLanguageCode = (languageCode) => {
    const normalized = String(languageCode || 'en')
        .trim()
        .toLowerCase()

    return translations[normalized] ? normalized : 'en'
}

export const getTranslation = (languageCode, key) => {
    const language = normalizeLanguageCode(languageCode)

    return (
        translations[language]?.[key] ??
        translations.en?.[key] ??
        key
    )
}

export const getTranslations = (languageCode) => {
    const language = normalizeLanguageCode(languageCode)

    return {
        ...translations.en,
        ...translations[language],
    }
}

export const getSupportedTranslationLanguages = () => {
    return Object.keys(translations)
}

export default translations
